export type Flavour = (typeof FLAVOURS)[number]['id'];

export interface Question {
  text: string;
  flavour: Flavour;
}

export function flavourInfo(id: Flavour) {
  return FLAVOURS.find((f) => f.id === id) ?? FLAVOURS[0];
}

