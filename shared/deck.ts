/** Pick a random question, skipping any in `exclude`; falls back to the full pool when everything is used. */
export function randomQuestion(exclude: Set<string> = new Set(), flavour: Flavour | 'any' = 'any'): string {
  const pool = flavour === 'any' ? DECK : DECK.filter((q) => q.flavour === flavour);
  const fresh = pool.filter((q) => !exclude.has(q.text));
  const source = fresh.length > 0 ? fresh : pool.length > 0 ? pool : DECK;
  return source[Math.floor(Math.random() * source.length)].text;
}

/** How many unused questions are left in a flavour (or the whole deck). */
export function remaining(exclude: Set<string>, flavour: Flavour | 'any' = 'any'): number {
  const pool = flavour === 'any' ? DECK : DECK.filter((q) => q.flavour === flavour);
  return pool.filter((q) => !exclude.has(q.text)).length;
}
